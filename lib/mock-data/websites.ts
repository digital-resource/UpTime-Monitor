// Generate additional websites for pagination testing
function generateWebsite(index: number): Website {
  const statuses: WebsiteStatus[] = ["up", "up", "up", "up", "up", "degraded", "paused", "unknown"];
  const providers: Provider[] = ["rocket_net", "webflow", "wordpress", "vercel", "aws", "shopify", "custom_server"];
  const clients = ["Apex Digital", "Meridian Tech", "Vertex Solutions", "Zenith Group", "Parallax Inc", "Orbit Media", "Nexus Corp"];
  const sources: Source[] = ["manual", "cloudflare_import", "webflow_import", "vercel_import"];

  const status = statuses[index % statuses.length];
  const provider = providers[index % providers.length];
  const client = clients[index % clients.length];
  const source = sources[index % sources.length];

  return {
    id: `ws_${String(100 + index).padStart(3, "0")}`,
    name: `${client} - Site ${index}`,
    url: `https://site${index}.example.com`,
    domain: `site${index}.example.com`,
    client,
    environment: "production",
    source,
    provider,
    tags: [`tag-${index % 5}`],
    internalNotes: null,
    status,
    monitoringState: status === "paused" ? "paused" : "enabled",
    httpStatus: status === "up" ? 200 : status === "degraded" ? 200 : null,
    responseTime: status === "up" ? 150 + (index * 37 % 500) : status === "degraded" ? 2500 + (index * 100 % 2000) : null,
    lastCheckedAt: new Date(now.getTime() - (index % 10) * 60000).toISOString(),
    lastSuccessAt: status !== "paused" ? new Date(now.getTime() - (index % 30) * 60000).toISOString() : daysAgo(3),
    lastFailureAt: index % 7 === 0 ? daysAgo(index % 20) : null,
    consecutiveFailures: 0,
    lastError: null,
    uptime24h: status === "up" ? 100 : 95 + (index % 5),
    uptime30d: 99 + (index * 0.01 % 0.99),
    uptime90d: 98.5 + (index * 0.01 % 1.49),
    ssl: {
      valid: true,
      expiresAt: daysAgo(-(30 + index % 150)),
      daysRemaining: 30 + index % 150,
      issuer: "Let's Encrypt",
      grade: "A",
      warningThreshold: 30
    },
    hasActiveIncident: false,
    activeIncidentId: null,
    checkInterval: 120,
    timeout: 30,
    failureThreshold: 3,
    recoveryThreshold: 1,
    expectedHttpStatus: 200,
    followRedirects: true,
    httpMethod: "GET",
    headers: {},
    contentKeyword: null,
    sslMonitoring: true,
    sslExpirationWarning: 30,
    notificationGroupId: "ng_001",
    maintenanceWindowId: null,
    createdAt: daysAgo(90 + index),
    updatedAt: new Date(now.getTime() - (index % 10) * 60000).toISOString(),
  };
}

